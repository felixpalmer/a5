type DataFile = {
  // Reads whole columns, in row order
  readColumns: (columns: string[]) => Promise<Record<string, any[]>>;
};

async function openDataFile(): Promise<DataFile> {
  const url = new URL(DATA_URL, window.location.origin).href;
  // One request for the end of the file gets both the footer (a few KB) and,
  // from Content-Range, the file's size, which hyparquet would otherwise
  // fetch with a HEAD request first. A server ignoring the range sends the
  // whole file, which serves just as well
  const response = await fetch(url, {headers: {Range: 'bytes=-16384'}});
  const tail = await response.arrayBuffer();
  const byteLength = Number(response.headers.get('Content-Range')?.split('/')[1]) || tail.byteLength;
  const metadata = parquetMetadata(tail);
  // Then fetch columns on demand
  const file =
    response.status === 206
      ? await asyncBufferFromUrl({url, byteLength})
      : {byteLength, slice: (start: number, end?: number) => tail.slice(start, end)};
  const rowCount = Number(metadata.num_rows);
  return {
    readColumns: async columns => {
      const result: Record<string, any[]> = {};
      for (const column of columns) result[column] = new Array(rowCount);
      await parquetRead({
        file,
        metadata,
        columns,
        // Column data arrives in chunks (one per row group)
        onChunk: ({columnName, columnData, rowStart}) => {
          const out = result[columnName];
          for (let i = 0; i < columnData.length; i++) out[rowStart + i] = columnData[i];
        }
      });
      return result;
    }
  };
}

// A5's planar lattice: a periodic tiling by one pentagon in four orientations
// (flavors). Lattice points are triples (x, y, z) with x + y + z = 0 or 1, and
// a point's flavor follows from that parity and the parity of y, as the A5
// curve's descent (sToCell) produces it. Positions are in the unit-scale
// lattice, which is a quintant at resolution LOGO_RESOLUTION scaled up by
// 2^LOGO_RESOLUTION
type LatticePoint = {x: number; y: number; z: number};
function latticeFlavor({x, y, z}: LatticePoint): number {
  const parity = x + y + z;
  return parity | ((parity ^ (y & 1)) << 1);
}

// The four flavors' pentagons, as vertex offsets from the pentagon's center
const FLAVOR_SHAPES = [0, 1, 2, 3].map(flavor => {
  // A lattice point of each flavor, see latticeFlavor
  const point = [
    {x: 0, y: 0, z: 0},
    {x: 0, y: 1, z: 0},
    {x: 0, y: 1, z: -1},
    {x: 0, y: 0, z: 1}
  ][flavor];
  const center = getPentagonCenter(0, 0, point, flavor);
  return getPentagonVertices(0, 0, point, flavor)
    .getVertices()
    .map(([vx, vy]) => [vx - center[0], vy - center[1]]);
});

// Render the text to a canvas, then keep the lattice pentagons whose centers
// land on it
function createLogoTiles(): LogoTiles {
  const fontSize = 200;
  const font = `900 ${fontSize}px "Helvetica Neue", Helvetica, Arial, sans-serif`;
  const canvas = document.createElement('canvas');
  const ctx = canvas.getContext('2d', {willReadFrequently: true})!;
  ctx.font = font;
  const metrics = ctx.measureText(LOGO_TEXT);
  const pad = 4;
  const width = Math.ceil(metrics.actualBoundingBoxLeft + metrics.actualBoundingBoxRight) + 2 * pad;
  const height = Math.ceil(metrics.actualBoundingBoxAscent + metrics.actualBoundingBoxDescent) + 2 * pad;
  canvas.width = width;
  canvas.height = height;
  ctx.font = font;
  ctx.fillStyle = '#fff';
  ctx.fillText(LOGO_TEXT, pad + metrics.actualBoundingBoxLeft, pad + metrics.actualBoundingBoxAscent);
  const pixels = ctx.getImageData(0, 0, width, height).data;

  let filled = 0;
  for (let i = 3; i < pixels.length; i += 4) {
    if (pixels[i] > 127) filled++;
  }

  // Size the patch of lattice so that the text covers ~LOGO_TILES pentagons
  const fill = filled / (width * height);
  // getArea is the shoelace sum without the halving (its sign gives the winding)
  const tileArea = Math.abs(getPentagonVertices(0, 0, {x: 0, y: 0, z: 0}, 0).getArea()) / 2;
  const spanX = Math.sqrt(((LOGO_TILES / fill) * tileArea * width) / height);
  const spanY = (spanX * height) / width;

  // Center the patch on quintant 0 (a triangle with its apex at the face
  // center), so every tile is a cell of that quintant with a place on the A5
  // curve. Corners: the apex and the two ends of the last row
  const lastRow = 2 ** LOGO_RESOLUTION - 1;
  const corners = [
    {x: 0, y: 0, z: 0},
    {x: -lastRow, y: lastRow, z: 0},
    {x: 0, y: lastRow, z: -lastRow}
  ].map(point => getPentagonCenter(0, 0, point, latticeFlavor(point)));
  const centerX = (corners[0][0] + corners[1][0] + corners[2][0]) / 3;
  const centerY = (corners[0][1] + corners[1][1] + corners[2][1]) / 3;

  // Pentagon centers move linearly with x and y (flavors aside, which only
  // shift them within a tile), so invert that to find the range of lattice
  // points covering the patch
  const origin = getPentagonCenter(0, 0, {x: 0, y: 0, z: 0}, 0);
  const stepX = getPentagonCenter(0, 0, {x: 1, y: 0, z: -1}, 0);
  const stepY = getPentagonCenter(0, 0, {x: 0, y: 2, z: -2}, 0);
  const [ax, ay] = [stepX[0] - origin[0], stepX[1] - origin[1]];
  const [bx, by] = [(stepY[0] - origin[0]) / 2, (stepY[1] - origin[1]) / 2];
  const determinant = ax * by - ay * bx;
  let minX = Infinity;
  let maxX = -Infinity;
  let minY = Infinity;
  let maxY = -Infinity;
  for (const [cx, cy] of [
    [centerX - spanX / 2, centerY - spanY / 2],
    [centerX + spanX / 2, centerY - spanY / 2],
    [centerX + spanX / 2, centerY + spanY / 2],
    [centerX - spanX / 2, centerY + spanY / 2]
  ]) {
    const x = (by * (cx - origin[0]) - bx * (cy - origin[1])) / determinant;
    const y = (ax * (cy - origin[1]) - ay * (cx - origin[0])) / determinant;
    minX = Math.min(minX, x);
    maxX = Math.max(maxX, x);
    minY = Math.min(minY, y);
    maxY = Math.max(maxY, y);
  }

  const kept: {x: number; y: number; flavor: number; order: number}[] = [];
  for (let y = Math.floor(minY) - 2; y <= Math.ceil(maxY) + 2; y++) {
    for (let x = Math.floor(minX) - 2; x <= Math.ceil(maxX) + 2; x++) {
      for (let parity = 0; parity < 2; parity++) {
        const point = {x, y, z: parity - x - y};
        const flavor = latticeFlavor(point);
        const center = getPentagonCenter(0, 0, point, flavor);
        // In logo units: width 1, centered on the origin
        const u = (center[0] - centerX) / spanX;
        const v = (center[1] - centerY) / spanX;
        const col = Math.floor((u + 0.5) * width);
        const row = Math.floor((0.5 - (v * width) / height) * height);
        if (col < 0 || row < 0 || col >= width || row >= height) continue;
        if (pixels[(row * width + col) * 4 + 3] <= 127) continue;
        // Position on the A5 curve, from the cell's center (see lonLatToCell)
        const triple = roundToTriple(FaceToIJ(center as any), LOGO_RESOLUTION);
        const order = Number(tripleToS(triple, LOGO_RESOLUTION));
        kept.push({x: u, y: v, flavor, order});
      }
    }
  }
  // Along the A5 curve, so consecutive tiles are neighbors and each chunk of
  // cells fills a patch shaped by the curve (see createCellGeometry)
  kept.sort((a, b) => a.order - b.order);

  const vertices = new Float32Array(kept.length * 10);
  const centers = new Float32Array(kept.length * 2);
  for (let i = 0; i < kept.length; i++) {
    const {x, y, flavor} = kept[i];
    const shape = FLAVOR_SHAPES[flavor];
    for (let k = 0; k < 5; k++) {
      // Shrunk towards the center so the grout between tiles shows
      vertices[i * 10 + k * 2] = x + (shape[k][0] / spanX) * 0.85;
      vertices[i * 10 + k * 2 + 1] = y + (shape[k][1] / spanX) * 0.85;
    }
    centers[i * 2] = x;
    centers[i * 2 + 1] = y;
  }

  return {vertices, centers, count: kept.length, height: height / width};
}

function valueToColor(
  value: number,
  minValue: number,
  maxValue: number,
  {ramp, scale}: Dataset,
  out: Float32Array,
  offset: number
) {
  if (scale === 'categorical') {
    // Categories index the ramp from 1, 0 for none
    const color = ramp[value - 1] ?? UNCATEGORIZED;
    for (let c = 0; c < 3; c++) out[offset + c] = color[c] / 255;
    return;
  }
  const transform =
    scale === 'log'
      ? (x: number) => Math.log10(1 + Math.max(x, 0))
      : scale === 'sqrt'
        ? (x: number) => Math.sqrt(Math.max(x, 0))
        : (x: number) => x;
  const lo = transform(minValue);
  const t = (transform(value) - lo) / (transform(maxValue) - lo || 1);
  const s = Math.min(Math.max(t, 0), 1) * (ramp.length - 1);
  const i = Math.min(Math.floor(s), ramp.length - 2);
  const f = s - i;
  for (let c = 0; c < 3; c++) {
    out[offset + c] = (ramp[i][c] + (ramp[i + 1][c] - ramp[i][c]) * f) / 255;
  }
}

// Every cell carries both its position on the globe and its tile in the logo,
// the vertex shader places it between the two using its chunk's progress. All
// datasets share this geometry, each supplies only its colors (createFill).
//
// Rows arrive in logo order (see prepare.sql), laid along the tiles, wrapping
// round to the first tile each time they run out, so row r takes tile
// r % tiles in layer floor(r / tiles). The globe positions come later
// (setGlobe), until then the cells can only sit in the logo
function createCellGeometry(chunks: ArrayLike<number>, logo: LogoTiles) {
  const n = chunks.length;
  const tile = new Float32Array(n * 15);
  const tileCenter = new Float32Array(n * 15);
  const seed = new Float32Array(n * 5);
  const chunk = new Float32Array(n * 5);
  const index = new Uint32Array(n * 9);

  let chunkCount = 0;
  for (let i = 0; i < n; i++) if (chunks[i] + 1 > chunkCount) chunkCount = chunks[i] + 1;
  const chunkSizes = new Uint32Array(chunkCount);

  for (let i = 0; i < n; i++) {
    const t = i % logo.count;
    // Each pass is a layer at its own depth, see layerSpacing
    const layer = Math.floor(i / logo.count);
    const cellSeed = Math.random();
    for (let k = 0; k < 5; k++) {
      const v = i * 5 + k;
      tile[v * 3] = logo.vertices[t * 10 + k * 2];
      tile[v * 3 + 1] = logo.vertices[t * 10 + k * 2 + 1];
      tileCenter[v * 3] = logo.centers[t * 2];
      tileCenter[v * 3 + 1] = logo.centers[t * 2 + 1];
      tileCenter[v * 3 + 2] = layer;
      seed[v] = cellSeed;
      chunk[v] = chunks[i];
    }
    chunkSizes[chunks[i]]++;
    index.set([i * 5, i * 5 + 1, i * 5 + 2, i * 5, i * 5 + 2, i * 5 + 3, i * 5, i * 5 + 3, i * 5 + 4], i * 9);
  }

  const geometry = new BufferGeometry();
  geometry.setAttribute('tile', new BufferAttribute(tile, 3));
  geometry.setAttribute('tileCenter', new BufferAttribute(tileCenter, 3));
  geometry.setAttribute('seed', new BufferAttribute(seed, 1));
  geometry.setAttribute('chunk', new BufferAttribute(chunk, 1));
  geometry.setIndex(new BufferAttribute(index, 1));
  // Nothing reads these back once they're on the GPU, free the JS copies.
  // three would compute a bounding sphere from them (after uploading) to sort
  // the mesh, so give it one. Its value doesn't matter, the mesh isn't culled
  geometry.boundingSphere = new Sphere(new Vector3(), 1);
  for (const attribute of [...Object.values(geometry.attributes), geometry.index!]) {
    (attribute as BufferAttribute).onUpload(freeArray);
  }
  // Placeholders for the globe positions, filled in by setGlobe
  geometry.setAttribute('position', new BufferAttribute(new Float32Array(n * 15), 3));
  geometry.setAttribute('center', new BufferAttribute(new Float32Array(n * 15), 3));
  return {geometry, chunkSizes, chunkCount, seed};
}

// Fill in the geometry's globe positions from computeGlobe's arrays, and
// return each chunk's center: the normalized sum of its cells' centers
function setGlobe(
  geometry: BufferGeometry,
  chunks: ArrayLike<number>,
  chunkCount: number,
  {position, center}: ReturnType<typeof computeGlobe>
) {
  const chunkCenters = new Float32Array(chunkCount * 3);
  for (let i = 0; i < chunks.length; i++) {
    for (let c = 0; c < 3; c++) chunkCenters[chunks[i] * 3 + c] += center[i * 15 + c];
  }
  for (let c = 0; c < chunkCount; c++) {
    const [x, y, z] = chunkCenters.subarray(c * 3, c * 3 + 3);
    const length = Math.hypot(x, y, z) || 1;
    chunkCenters.set([x / length, y / length, z / length], c * 3);
  }
  for (const [name, array] of [
    ['position', position],
    ['center', center]
  ] as const) {
    const attribute = geometry.getAttribute(name) as BufferAttribute;
    attribute.array = array;
    attribute.needsUpdate = true;
    attribute.onUpload(freeArray);
  }
  return chunkCenters;
}

// computeGlobe in a worker, so the main thread stays free to animate the logo
// in meanwhile. Falls back to computing it here without worker support
function computeGlobeAsync(cells: BigUint64Array): Promise<ReturnType<typeof computeGlobe>> {
  let worker: Worker;
  try {
    worker = new Worker(new URL('./globe-worker.ts', import.meta.url));
  } catch {
    return Promise.resolve(computeGlobe(cells));
  }
  return new Promise(resolve => {
    worker.onmessage = event => {
      worker.terminate();
      resolve(event.data);
    };
    worker.onerror = () => {
      worker.terminate();
      resolve(computeGlobe(cells));
    };
    worker.postMessage({cells});
  });
}

function freeArray(this: {array: unknown}) {
  this.array = null;
}

// A dataset's cell colors, per vertex, for the shared geometry's fill
// attribute. seed is the geometry's per-vertex random value
function createFill(values: ArrayLike<number>, dataset: Dataset, seed: Float32Array) {
  const n = values.length;
  let minValue = Infinity;
  let maxValue = -Infinity;
  for (let i = 0; i < n; i++) {
    if (values[i] < minValue) minValue = values[i];
    if (values[i] > maxValue) maxValue = values[i];
  }
  const fill = new Float32Array(n * 15);
  const color = new Float32Array(3);
  for (let i = 0; i < n; i++) {
    valueToColor(values[i], minValue, maxValue, dataset, color, 0);
    // Flat country colors get a slight per-cell lightening so the tiles show
    if (dataset.scale === 'categorical') for (let c = 0; c < 3; c++) color[c] *= 1 + seed[i * 5] * 0.22;
    for (let k = 0; k < 5; k++) fill.set(color, (i * 5 + k) * 3);
  }
  const attribute = new BufferAttribute(fill, 3);
  attribute.onUpload(freeArray);
  return attribute;
}

// Pulls back slightly before accelerating away
function easeInBack(t: number, overshoot = 1.2): number {
  return (overshoot + 1) * t * t * t - overshoot * t * t;
}

// Damped spring from 0 to 1, overshooting by ~8% before settling
function springIn(t: number): number {
  return t >= 1 ? 1 : 1 - Math.exp(-7 * t) * Math.cos(9 * t);
}

