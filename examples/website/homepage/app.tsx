// Legend: the active dataset's color ramp as a thin bar under its label below
// the globe, low on the left, or for categories their colors side by side.
// Drawn in the scene so it blooms like the cells
const RAMP_STOPS = 8;

const LEGEND_VERTEX_SHADER = /* glsl */ `
varying vec2 vUv;
void main() {
  vUv = uv;
  gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
}
`;

const LEGEND_FRAGMENT_SHADER = /* glsl */ `
uniform vec3 ramp[${RAMP_STOPS}];
// 0 for a continuous ramp over all the stops, else that many discrete colors
uniform float steps;
uniform float opacity;
varying vec2 vUv;
void main() {
  float x = clamp(vUv.x, 0.0, 1.0);
  if (steps > 0.0) {
    float s = x * steps;
    int i = int(min(floor(s), steps - 1.0));
    // A small gap between the colors
    float edge = fract(s);
    float alpha = edge < 0.08 && s > 1.0 ? 0.0 : 1.0;
    gl_FragColor = vec4(ramp[i], opacity * alpha);
    return;
  }
  float s = x * float(${RAMP_STOPS - 1});
  int i = int(min(floor(s), float(${RAMP_STOPS - 2})));
  vec3 color = mix(ramp[i], ramp[i + 1], s - float(i));
  gl_FragColor = vec4(color, opacity);
}
`;

// Full-screen background: the dark gradient, a faint nebula and three layers
// of twinkling stars, clumped by noise and shifted slightly as the globe
// turns so the nearer layers show a little parallax
const SKY_VERTEX_SHADER = /* glsl */ `
void main() {
  gl_Position = vec4(position.xy, 0.0, 1.0);
}
`;

const SKY_FRAGMENT_SHADER = /* glsl */ `
uniform vec2 resolution;
uniform float pixelRatio;
uniform float time;
// Parallax offset, in view heights
uniform vec2 drift;
// Scales the stars' core size and brightness
uniform float starSize;
uniform float starIntensity;

float hash(vec2 p) {
  vec3 p3 = fract(vec3(p.xyx) * 0.1031);
  p3 += dot(p3, p3.yzx + 33.33);
  return fract((p3.x + p3.y) * p3.z);
}

float noise(vec2 p) {
  vec2 i = floor(p);
  vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(mix(hash(i), hash(i + vec2(1.0, 0.0)), u.x), mix(hash(i + vec2(0.0, 1.0)), hash(i + vec2(1.0, 1.0)), u.x), u.y);
}

float fbm(vec2 p) {
  float value = 0.0;
  float amplitude = 0.5;
  for (int i = 0; i < 5; i++) {
    value += amplitude * noise(p);
    p *= 2.03;
    amplitude *= 0.5;
  }
  return value;
}

// At most one star per grid cell, cellsPerHeight cells across the view's
// height, a cell holding one with probability density
vec3 stars(vec2 uv, float cellsPerHeight, float density, float seed) {
  vec2 grid = uv * cellsPerHeight;
  vec2 id = floor(grid);
  float h = hash(id + seed);
  if (h > density) return vec3(0.0);
  vec2 center = 0.2 + 0.6 * vec2(hash(id + seed + 11.3), hash(id + seed + 27.1));
  // Distance from the star in pixels, with a Gaussian core of 0.35-0.9px
  float d = length(fract(grid) - center) / cellsPerHeight * resolution.y;
  float size = mix(0.35, 0.9, pow(hash(id + seed + 5.7), 3.0)) * pixelRatio * starSize;
  float core = exp(-d * d / (size * size));
  float twinkle = 0.75 + 0.25 * sin(time * (0.5 + 2.0 * hash(id + seed + 3.3)) + h * 40.0);
  vec3 tint = mix(vec3(0.75, 0.8, 1.0), vec3(1.0, 0.9, 0.75), hash(id + seed + 9.1));
  return tint * core * twinkle;
}

void main() {
  vec2 uv = gl_FragCoord.xy / resolution.y;
  // Same gradient as the page background, #000 at the bottom to #223 at the top
  vec3 color = vec3(0.133, 0.133, 0.2) * (gl_FragCoord.y / resolution.y);

  // Low frequency noise clumps the stars and lights a faint nebula
  float clump = smoothstep(0.3, 0.8, fbm(uv * 1.2 + drift * 0.2 + 7.0));
  float nebula = fbm(uv * 2.0 + drift * 0.3 + vec2(0.0, 3.0));
  color += vec3(0.25, 0.15, 0.45) * pow(nebula, 3.0) * 0.25 * clump;

  // Far to near: smaller, denser and fainter to sparser and brighter
  vec3 starlight = stars(uv + drift * 0.2, 90.0, 0.03 + 0.12 * clump, 1.0) * 0.3;
  starlight += stars(uv + drift * 0.5, 40.0, 0.03 + 0.1 * clump, 17.0) * 0.4;
  starlight += stars(uv + drift, 16.0, 0.06, 43.0) * 0.6;
  color += starlight * starIntensity;

  gl_FragColor = vec4(color, 1.0);
}
`;

